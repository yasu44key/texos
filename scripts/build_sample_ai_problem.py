# -*- coding: utf-8 -*-
"""サンプルAI問題解決 — 問題を入れる → AI が答える → 別の AI が要約する。

規約: docs/AIエージェント向け_フロー構築規約.md
  §3-15 入口は付箋（IN は口を明示するだけ）
  §3-1  AI カードの入力は1本ずつ（役割は role="system" で入力に数えない）
  §3-10 中間出力はファイルにならないので記録カードで残す
  §3-6  AI カードに timeout は指定しない
"""
import sys
sys.path.insert(0, r"C:\Users\yoshi\dev\texos\scripts")
from texos_flow import Project

DEST = r"F:\yoshi\Documents\TexoS\サンプルAI問題解決"
MODEL = "gemma4:latest"          # §2-1 実機の ollama list で確認したもの

p = Project(DEST, model=MODEL)

# ---- 入口（§3-15）--------------------------------------------------------
問題 = p.note(
    "問題（ここを書き換える）\n"
    "----------------------------------------\n"
    "この線から下に、解いてほしい問題を書いてください。\n"
    "書き換えたら、いちばん下の「要約」カードの ▶ を押します。\n"
    "----------------------------------------\n"
    "\n"
    "在宅勤務を週3日に増やしたいが、チームの雑談が減って\n"
    "新人が質問しづらくなっている。どうすればよいか。\n",
    440, 40)

入口 = p.op_in("問題の入口", 440, 300)

# ---- 一段目：答える ------------------------------------------------------
役割1 = p.note(
    "役割：回答担当（ここを書き換える）\n"
    "----------------------------------------\n"
    "あなたは実務家です。渡された問題に日本語で答えてください。\n"
    "・まず問題を一文で言い換える（勝手に前提を足さない）\n"
    "・原因の見立てを3つまで\n"
    "・打ち手を具体的に3つ。それぞれ「誰が・いつ・何をするか」まで書く\n"
    "・最後に確信度（高/中/低）と、その確信度になった理由を一文で。\n"
    "  理由の無い確信度は書かない。\n"
    "・情報が足りないなら、答えを作らずに何が足りないかを書く。",
    20, 420)

回答 = p.ai("AI①：答える", 440, 460, system="", temperature=0.3, prefix="回答")
記録回答 = p.tap("記録：回答の全文", 440, 660, prefix="回答")

# ---- 二段目：要約する ----------------------------------------------------
役割2 = p.note(
    "役割：要約担当（ここを書き換える）\n"
    "----------------------------------------\n"
    "渡された文章を日本語で要約してください。\n"
    "・冒頭に「結論：」の一文（40字以内）\n"
    "・次に箇条書きで最大5行。1行30字程度\n"
    "・元の文章に無いことは足さない。評価も感想も書かない\n"
    "・元の文章が確信度に触れていたら、最後の1行にそのまま残す",
    20, 820)

要約 = p.ai("AI②：要約する", 440, 860, system="", temperature=0.2, prefix="要約")
記録要約 = p.tap("記録：要約", 440, 1060, prefix="要約")

出口 = p.op_out("要約（ここの ▶ を押す）", 440, 1260)

# ---- 配線 ---------------------------------------------------------------
p.flow(問題, 入口)
p.flow(入口, 回答)
p.flow(役割1, 回答, role="system")      # 役割ポート＝入力に数えない（§3-9）
p.flow(回答, 記録回答)
p.flow(記録回答, 要約)                   # 記録は素通し。要約の通常入力は1本だけ（§3-1）
p.flow(役割2, 要約, role="system")
p.flow(要約, 記録要約)
p.flow(記録要約, 出口)

# ---- 読みやすさ ---------------------------------------------------------
p.shape(400, 0, 320, 400, "① 問題を入れる")
p.shape(0, 400, 720, 400, "② AI が答える")
p.shape(0, 800, 720, 400, "③ 別の AI が要約する")

p.note(
    "この面の使い方（繋がっていない説明の付箋）\n"
    "----------------------------------------\n"
    "1. 上の「問題（ここを書き換える）」をダブルクリックして問題を書く\n"
    "2. いちばん下の「要約（ここの ▶ を押す）」の ▶ を押す\n"
    "3. フォルダに 回答.md と 要約.md ができる（毎回上書き）\n"
    "\n"
    "・AI の担当（役割）は左の2枚の付箋に書いてあります。\n"
    "  そのまま書き換えれば、答え方・要約の仕方が変わります。\n"
    "・使用モデル: " + MODEL + "（AIカードの設定で変えられます）\n"
    "・答えの全文は「記録：回答の全文」が 回答.md に残します。\n"
    "  途中だけ見たいときは、そのカードの ▶ を押すこともできます。",
    900, 40)

p.view()
p.save()
p.link_into(r"F:\yoshi\Documents\TexoS")
