# -*- coding: utf-8 -*-
"""「AIカードを2枚並べて、課題の答えをもう1枚のAIが要約する」フロー。

AI エージェント向けマニュアル（docs/AIエージェント向け_フロー構築規約.md）だけを見て
組めるかを試すための、いちばん簡単な課題の**模範解答**。依頼文はこれ:

    「AIカードを準備して、課題を入力すると、その出力を再度AIが要約するフローを構築して」

  [課題（ここを書き換える）] ─▶ [IN] ─▶ [AI① 答える] ─▶ [AI② 要約する] ─▶ 要約.md

規約のどこを踏んでいるか（採点用）:

- §2-1  モデルは実機で確認して決める（`ollama list` の結果から選ぶ。写経しない）
- §3-15 「課題を入力する」の実体は**付箋**。IN カードは中身を持てないので、
        付箋の手前に置くのではなく、付箋の**次**に「ここが口です」と添える
- §3-1  AI カードの通常入力は1本。ここは一本道なので束（cat）は要らない
- §3-4  終端＝AI②。`prefix="要約"` を付けたので毎回 `要約.md` を上書きする
- §1-1  途中の AI① だけを ▶ すれば、答えだけを見ることもできる（同じグラフで両方できる）
- §3-6  AI カードに `timeout_secs` を付けない（ローカル LLM は分単位かかる）

より TexoS らしくするなら、2枚の system を**役割の付箋**にして `role="system"` で
繋ぐ（§3-9）。誰が何の担当かがキャンバスから読めて、その場で書き換えられる。
ここでは依頼文どおり「2枚目に『要約する』と入れる」最小形にしてある。
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from texos_flow import Project  # noqa: E402

ROOT = r"F:\yoshi\Documents\TexoS\カード実験_二段AI"

# §2-1: この環境の `ollama list` に実在するものを選んだ（9.6GB・常用サイズ）。
# 他所へ持っていくときは、必ず相手の実機で確認して差し替えること。
MODEL = "gemma4:latest"

p = Project(ROOT, model=MODEL)

課題 = p.note(
    "課題（ここを書き換える）\n\n"
    "なぜ紙の手帳を使い続ける人がいるのか、\n"
    "デジタルツールと比べて説明してください。",
    60, 80, width=340,
)

入口 = p.op_in(
    "IN（入口）", 460, 110,
    memo="素通しの口。中身は持てない —— 書き換えるのは左の付箋のほう（§3-15）",
)

答える = p.ai(
    "AI① 答える", 760, 110,
    system=(
        "あなたは丁寧な解説者です。渡された課題に、根拠を添えて答えてください。"
        "見出しを付けて構造化し、400〜600字程度でまとめること。"
    ),
    prefix="回答",   # 途中だけ見たいときに ▶ を押すと 回答.md ができる（§1-1）
)

要約 = p.ai(
    "AI② 要約する", 1080, 110,
    system=(
        "渡された文章を要約してください。"
        "箇条書き3点だけで書き、1点は40字以内。前置きも結びも書かないこと。"
    ),
    prefix="要約",   # 終端の prefix が出力名を決める（§3-4）
)

p.flow(課題, 入口)
p.flow(入口, 答える)
p.flow(答える, 要約)

p.shape(430, 40, 880, 200, "AI 2段（答える → 要約する）")
p.view(0, 0, 0.75)
p.save(reset=True)

# 親（＝この実験フォルダの置き場）の面に入口を1枚だけ貼る（§5-2）。
p.link_into(os.path.dirname(ROOT))
