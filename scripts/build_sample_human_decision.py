# -*- coding: utf-8 -*-
"""サンプルフロー「課題に人の判断を挟む（2パス）」を初期状態で組む（v1.8 ③問い合わせカード）。

TexoS のフローはふつう一気に流れてしまう。このサンプルの主題は、**人が判断する場所を
グラフの上に置く**こと。AI に原案を書かせたところでいったん止め、人が方針を決めてから、
その判断を材料にして最終の成果物を作らせる。

  ■ 1パス目 … ▶ を押す → AI が原案を書く → 「答え待ち」で止まる（エラーではない）
  ■ 2パス目 … 答えの付箋に判断を書いて、もう一度 ▶ → 実施計画ができる

  課題(付箋) ──▶ 原案(AI) ──▶ 記録：原案 ──▶ 人の判断を聞く ──▶ 記録：判断 ──┐
       │                                          ▲                            │
       │                                   答えの付箋（例示つき）               │
       └────────────────────────────────────────────────────────▶ 束（課題＋判断）
                                                                        │
                                                            手順化(AI) ─┘──▶ 実施計画.md

■ 問い合わせカードに入る矢印は2種類
  ① ふつうの矢印 ＝ 何について聞くか（材料）
  ② 役割＝答えの矢印 ＝ 答えを書く付箋。ここでは**書き方の例示を入れて先に置いてある**。
     `>` で始まる行は答えとして読まないので、例示を置いても「答えたこと」にならない。
  （答えの付箋を置かずに実行すると、質問と材料を引用した付箋が自動生成される。
    先に置いてあるこのサンプルでは自動生成は起きないので、原案は 原案.md を開いて読む。）

■ 「答えが入ったら上流を動かさない」スイッチ（`skip_upstream=True`）
問い合わせカードは既定では、答えが書いてあっても上流を評価する。そのままだと
**2パス目に原案の AI が走り直し、人が読んだ案と別物になる**。このサンプルでは
スイッチを入れてあるので、答えが入っている限り原案は作り直されない（AI も呼ばれない
＝2パス目は速い）。答えを消せば、また上流から動く。

■ 束に原案を入れていない理由
決定の材料は「課題＋人の判断」。原案は**人が判断するための材料**であって、決定そのものは
人の言葉で書かれている、という切り分け。原案の文面も最終材料にしたいなら、束へ
**記録が作った実身カード（原案.md）**を繋ぐ（実身は「ファイルの今」を読む）。
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from texos_flow import Project  # noqa: E402

ROOT = r"F:\yoshi\Documents\TexoS\サンプル_人の判断を挟む"

p = Project(ROOT)

# --- 材料 ------------------------------------------------------------------
kadai = p.note(
    "【課題】\n"
    "社内の共有フォルダが増えすぎて、どこに何があるか誰も把握できていない。\n"
    "半年で整理したいが、通常業務を止めることはできない。\n"
    "使える人手は週に2人日、予算はほぼ無し。",
    60, 60, width=380,
)  # 束の1本目にもなる（前提は下流まで持ち回る＝規約 §4-3）

yakuwari_gen = p.note(
    "あなたは社内の業務改善担当です。渡された課題に対して、\n"
    "取り得る方針を3つ、それぞれ1〜2行で挙げてください。\n"
    "どれを推すかは書かず、選ぶのは人に任せること。\n"
    "前置き・見出しは書かないこと。",
    60, 300, width=380,
)  # 役割ポート（原案AI）。「決めない・並べるだけ」がこのカードの担当

kotae = p.note(
    "> 【問い】原案（原案.md）を読んで、どの方針で進めるか決めてください。理由も1行で。\n"
    "> ── ここから下に答えを書いてください（「>」で始まる行は答えになりません）\n"
    ">\n"
    "> 【書き方の例】\n"
    "> 方針: 全部を整理しない。よく使う上位2割だけ先に片づける。\n"
    "> 理由: 週2人日では全体棚卸しは終わらず、効果も薄いため。\n"
    "> 追加: 分類の見直しは月1でまとめて行う。\n"
    ">\n"
    "> 例をそのまま使ってもよいし、消して自分の言葉で書いてもよい\n"
    "> （「>」の行は残しておいて、その下に書くのが楽）。\n",
    60, 620, width=420,
)  # 答えの箱。例示は引用行なので「答え」に混ざらない

yakuwari_plan = p.note(
    "あなたは社内の業務改善担当です。渡された課題と、決まった方針に沿って、\n"
    "今週から始められる具体的な手順を5つまでの箇条書きで書いてください。\n"
    "方針から外れる提案はしないこと。前置き・見出しは書かないこと。",
    60, 1060, width=380,
)  # 役割ポート（手順化AI）

setsumei = p.note(
    "【このサンプルの使い方 — 2パスで進みます】\n"
    "1パス目) 右下「手順化」の ▶ を押す\n"
    "   → AI が原案を書き、原案.md ができます\n"
    "   → そこで「答え待ち」で止まります（エラーではありません）\n"
    "2パス目) 原案.md を開いて読み、左下の「答えの付箋」の例示を参考に、\n"
    "   いちばん下へ自分の判断を書く\n"
    "   → もう一度「手順化」の ▶ → 実施計画1.md ができます\n"
    "\n"
    "・答えを消して空にすれば、また「答え待ち」に戻ります（何度でも試せます）\n"
    "・書いた判断は 人の判断.txt として残ります（記録カード）\n"
    "・課題の付箋を書き換えれば、同じ仕組みを別の課題に使い回せます\n"
    "・「人の判断を聞く」は設定で〈答えが入ったら＝上流を動かさない〉にしてあります。\n"
    "  そのため2パス目は原案を作り直さず（AI も呼ばれず）すぐ終わります。\n"
    "  作り直してほしいときは、この設定を〈上流をもう一度動かす〉に戻してください。",
    560, 1060, width=460,
)  # 説明用。フローには繋がない（繋ぐ付箋と繋がない付箋は同じ見た目＝規約 §3-5）

# --- カード ----------------------------------------------------------------
genan = p.ai(
    "原案", 560, 60, system="（役割ポートで上書きされます）", prefix="原案",
    memo="1パス目で走る。決めるのは人なので、ここでは方針を並べるだけ。",
)

kiroku_genan = p.tap(
    "記録：原案", 560, 260, prefix="原案",
    memo="原案をファイルに残す。人はこの 原案.md を開いて読んでから判断する。",
)

toi = p.ask(
    "人の判断を聞く", 560, 460,
    question="原案を読んで、どの方針で進めるか決めてください。理由も1行で。",
    prefix="人の判断",
    skip_upstream=True,
    memo="答えが空のあいだは no-data＝ここから先へ進まない（エラーではない）。"
         "答えが入ったら上流を動かさない＝2パス目に原案が作り直されない。",
)

kiroku_handan = p.tap(
    "記録：判断", 560, 660, prefix="人の判断",
    memo="判断をファイルに残す（あとで「なぜこの方針にしたか」を読み返せる）。",
)

taba = p.cat(
    "束（課題＋判断）", 980, 660, separator="rule", prefix="材料",
    memo="1本目=課題（前提を持ち回る）／2本目=人の判断。原案は入れない（上の注記参照）。",
)

shori = p.ai(
    "手順化", 980, 880, system="（役割ポートで上書きされます）", prefix="実施計画",
    memo="判断が入って初めて走る（1パス目は上流が no-data なので呼ばれない）。",
)

# --- 配線（束の順序＝繋いだ順なので、課題を先に繋ぐ）------------------------
p.flow(yakuwari_gen, genan, role="system")
p.flow(kadai, genan)
p.flow(genan, kiroku_genan)
p.flow(kiroku_genan, toi)           # ①材料の矢印: 何について聞くか
p.flow(kotae, toi, role="answer")   # ②答えの矢印: ここに書いたものが答えになる
p.flow(toi, kiroku_handan)
p.flow(kadai, taba)                 # 束の1本目＝課題
p.flow(kiroku_handan, taba)         # 束の2本目＝人の判断
p.flow(yakuwari_plan, shori, role="system")
p.flow(taba, shori)

p.shape(40, 420, 480, 480, "人が判断するところ", fill="#d9a05a", opacity=0.10)
p.view(x=20, y=20, scale=0.65)
p.save()
