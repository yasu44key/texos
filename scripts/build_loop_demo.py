# -*- coding: utf-8 -*-
"""v1.8 ④反復カードの動作確認プロジェクトを組む（使い捨てではなく手本として残す）。

確かめたいのは4つ:
  1. 反復が本当に上流を引き直すか（AI が周ごとに走るか）
  2. 前周の結果が戻り矢印で上流に届くか（1周目だけ空）
  3. 停止条件（出力に「合格」）で止まるか／出なければ上限で止まるか
  4. 反復の中の記録カードが周ごとに残るか（各周_1 / 各周_2 …）

形は「AI設計審査」と同じ骨（判定 → 直して再判定）を最小の5枚にしたもの。

  お題(付箋) ─┐
              束 ── 推敲(AI) ── 記録 ── 反復 ──▶（終端＝結論）
  役割(付箋) ─────────↑（役割ポート）      │
              ↑───────────────────────────┘（役割＝前周の結果）
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from texos_flow import Project  # noqa: E402

ROOT = r"F:\yoshi\Documents\TexoS\カード実験_反復"

p = Project(ROOT)

odai = p.note(
    "次の一文を、意味を変えずに読みやすくしてください。\n\n"
    "「当システムにおきましては、利用者様がファイルを保存された場合において、"
    "当該ファイルは自動的にバックアップが取得される仕組みとなっております。」",
    60, 60, width=380,
)  # お題。反復しても変わらない前提なので、束の1本目に固定で入れる（枠は持ち回る）

yakuwari = p.note(
    "あなたは日本語の推敲者です。材料は「お題」と、あれば「前回の案」です。\n"
    "前回の案があれば、そこから1点だけ具体的に直して、直した後の全文だけを出力してください。\n"
    "前回の案が無ければ、お題を推敲した全文を出力してください。\n"
    "説明・前置き・見出しは書かないこと。\n"
    "もうこれ以上直すところが無いと判断したときだけ、全文の最後の行に「合格」とだけ書いてください。",
    60, 300, width=380,
)  # 役割ポート（role="system"）で AI のシステムプロンプトに。入力に数えない＝ファンアウトしない

taba = p.cat(
    "束（お題＋前周）", 520, 60, separator="rule", prefix="材料",
    memo="1本目=お題（固定）／2本目=前周の結果。1周目は2本目が空で届く。",
)

ai = p.ai(
    "推敲", 520, 240, system="（役割ポートで上書きされます）", prefix="案",
    memo="周ごとに走る。上流のメモを反復カードが捨てるので、2周目も実際に呼ばれる。",
)

kiroku = p.tap(
    "各周の記録", 520, 420, prefix="各周",
    memo="反復の中にあるので 各周_1.md / 各周_2.md … と周ごとに残る"
         "（固定名のままだと後の周に上書きされて消える）。",
)

hanpuku = p.loop(
    "反復（合格まで・最大3周）", 520, 600, max_rounds=3, until_contains="合格",
    memo="停止条件は決定的ルール（出力に「合格」を含む）。出なければ上限3周で止まる。"
         "終端なのでここの出力が結論として実身になる。",
)
# 終端カードの出力名（run_flow は終端 spec の prefix で名前を決める）
p._cards[hanpuku]["spec"]["prefix"] = "結論"

p.flow(odai, taba)
p.flow(hanpuku, taba, role="previous")   # 束の2本目＝前周の結果（評価では遡らない）
p.flow(yakuwari, ai, role="system")
p.flow(taba, ai)
p.flow(ai, kiroku)
p.flow(kiroku, hanpuku)

p.view(x=20, y=20, scale=0.75)
p.save()
