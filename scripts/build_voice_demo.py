"""音声反射カード（v1.10）の手本プロジェクト「音声反射サンプル」を組む。

docs/V1.10_音声反射カード計画.md の今の仕組み（2026-10-11・会話エージェント版）を、分岐ごとに試せる形で並べる:
  A. 会話コマンド — 音声カード1枚から5つの分岐。発話は会話履歴ごと AI に渡り、AI が
     「どのカードを実行するか／続きを待つか／止める・中止・リセットか」を分類する。
       メモして          … 聞き取り中のデモ（「メモして」→ 話す →「以上」で確定）
       英訳して          … 言い方を複数持つ（say=：英語にして・翻訳して）
       要約して          … 長めに話した内容を3行に
       英語で要約して    … 2段のフロー（要約 → 英訳）を1つのコマンドで
       文字数を数えて    … AI を使わない普通のフィルタ（text_count）
  B. 口述 — 話し終えるたびに全文を受け皿へ入れ、清書とキーワード抽出の2本を同時に走らせる。
マイクは1つなので、稼働できる音声カードは1枚（使う方だけ「▶ 稼働開始」）。

カードのコメント（memo）は、AI がコマンドを判定するときの説明として渡る（voice.rs agent_prompt）。

使い方: python scripts/build_voice_demo.py [フォルダ] [--model gemma4:latest] [--reset]
"""
import argparse
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from texos_flow import Project  # noqa: E402

ap = argparse.ArgumentParser()
ap.add_argument("root", nargs="?", default=r"X:\Yoshiki\TexoS\音声反射サンプル")
ap.add_argument("--model", default="gemma4:latest")
ap.add_argument("--reset", action="store_true")
a = ap.parse_args()

p = Project(a.root, model=a.model)

# ════════════════════════════════════════════════════════════════
# A. 会話コマンド
# ════════════════════════════════════════════════════════════════
p.shape(20, 20, 1560, 1300, "A. 会話コマンド — 話しかけると AI が分岐を選ぶ", fill="#d9a04a", opacity=0.10)
p.note(
    "使い方（会話コマンド）\n"
    "1. 「会話コマンド」の ▶ 稼働開始（初回は音声環境の構築とモデル取得）\n"
    "   カードの下のパネルに 聞き取り中 と出たら話せる\n"
    "2. 下の「試す言い方」を話す。返事はすぐ声で返り、\n"
    "   実行したフローは終わると「○○、終わりました」と報告\n"
    "\n"
    "しくみ\n"
    "・話し終えて約1.2秒で区切り、会話の流れごと AI に渡す\n"
    "・AI は右の5枚から選ぶ（カード名＋コメントが選択肢の説明）\n"
    "・会話コマンド →「書き出し」→ 発話.txt：中身はここに入り、\n"
    "  そこから各フローへ流れる（矢印の先を別のファイルにすれば受け皿が変わる）\n"
    "・会話の記録は 発話ログ.md に追記される\n"
    "・パネルの欄に文字を打っても話しかけたのと同じ\n"
    "・カードを足して矢印を引けば、分岐が増える",
    60, 80, width=360)
p.note(
    "試す言い方\n"
    "【メモして】聞き取り中のデモ\n"
    "  「メモして」→「明日は10時に歯医者」→「保険証も持っていく」→「以上」\n"
    "  （途中の中身は 発話.txt に追記されていく）\n"
    "  一度に:「メモして、牛乳を買う」\n"
    "【英訳して】「これを英語にして、今日はいい天気です」\n"
    "【要約して】「要約して」→ 長めに話す →「以上」\n"
    "【英語で要約して】「英語で要約して」→ 話す →「以上」\n"
    "【文字数を数えて】「文字数を数えて、吾輩は猫である」\n"
    "\n"
    "【止める・中止・リセット】これも AI が判断する\n"
    "  「ちょっと止めて」… 読み上げを止める\n"
    "  「全部キャンセルして」… 実行中のフローを中断\n"
    "  「最初からやり直そう」… 会話の履歴を消す\n"
    "【ただの会話】「今日は何曜日だっけ」→ 返事だけ",
    60, 520, width=360)

cmd = p.voice("会話コマンド", 470, 90, mode="command", say_out="音声/発話.txt",
              classifier="ai", ai_model=a.model,
              memo="稼働中はカードの下に状態パネル（聞き取り中・入力レベル・直近の発話と判定）が出ます")
inbox = p.file("音声/発話.txt", "", 700, 90,
               memo="発話の中身が入る受け皿。聞き取り中は話すたびに追記される")
p.request(cmd, inbox)   # 「書き出し」の矢印＝これが受け皿を決める
p.file("音声/発話ログ.md", "# 発話ログ\n\n", 950, 90,
       memo="会話の記録（追記）。🎙マイク ⌨パネルの欄 📄会話へ送る／🤖返事 ▶実行 ✓完了")

# 分岐1: メモして
memo_role = p.note(
    "役割：メモ係（ここを書き換える）\n"
    "入力は音声認識の結果。誤認識らしい語は文脈で直し、\n"
    "箇条書きメモに整える。前置き・説明は書かない。",
    470, 300, width=300)
memo_ai = p.ai("メモして", 950, 290, prefix="メモ", seq=1, temperature=0.2,
               memo="話した内容を箇条書きのメモに残す")
p.flow(inbox, memo_ai)
p.flow(memo_role, memo_ai, role="system")

# 分岐2: 英訳して（言い方を複数）
en_role = p.note(
    "役割：翻訳係（ここを書き換える）\n"
    "入力は音声認識の結果（日本語）。自然な英語に訳し、\n"
    "訳文だけを出す。",
    470, 500, width=300)
en_ai = p.ai("英訳して", 950, 490, prefix="英訳", temperature=0.2,
             memo="日本語の内容を英語に訳す")
p.flow(inbox, en_ai)
p.flow(en_role, en_ai, role="system")

# 分岐3: 要約して
sum_role = p.note(
    "役割：要約係（ここを書き換える）\n"
    "入力は音声認識の結果。誤認識は文脈で直し、\n"
    "要点を3行以内にまとめる。前置きは書かない。",
    470, 700, width=300)
sum_ai = p.ai("要約して", 950, 690, prefix="要約", seq=1, temperature=0.2,
              memo="長めに話した内容を3行に要約する")
p.flow(inbox, sum_ai)
p.flow(sum_role, sum_ai, role="system")

# 分岐4: 英語で要約して（2段: 要約 → 英訳）
sum2_role = p.note(
    "役割：要約係（2段目へ渡す）\n"
    "入力は音声認識の結果。要点を3行以内の日本語にまとめる。",
    470, 900, width=300)
sum2_ai = p.ai("要約（英訳の前段）", 800, 890, temperature=0.2,
               memo="2段フローの1段目（ここは単独では呼ばれない）")
en2_role = p.note(
    "役割：翻訳係（2段目）\n"
    "入力の日本語の要約を、自然な英語に訳す。訳文だけを出す。",
    1050, 1030, width=300)
en2_ai = p.ai("英語で要約して", 1120, 890, prefix="英語の要約", temperature=0.2,
              memo="話した内容を要約してから英語に訳す（要約→英訳の2段）")
p.flow(inbox, sum2_ai)
p.flow(sum2_role, sum2_ai, role="system")
p.flow(sum2_ai, en2_ai)
p.flow(en2_role, en2_ai, role="system")

# 分岐5: 文字数を数えて（AI を使わないフィルタ）
count = p.builtin("文字数を数えて", 950, 1150, name="text_count", mode="all",
                  accept_mime="text/*", prefix="文字数",
                  memo="話した内容の行数・単語数・文字数を数える（AI を使わない普通のフィルタ）")
p.flow(inbox, count)

# 音声カード → 各分岐（リクエスト矢印）。say= は AI への言い方の例にもなる。
p.request(cmd, memo_ai)
p.request(cmd, en_ai, say=["英訳して", "英語にして", "翻訳して"])
p.request(cmd, sum_ai, say=["要約して", "まとめて"])
p.request(cmd, en2_ai)
p.request(cmd, count, say=["文字数を数えて", "何文字か数えて"])

# 会話へ送る: マイク以外の入力を同じ会話へ（テキストの例）
p.note(
    "会話へ送る（マイク以外の入力）\n"
    "送るテキスト.txt を書き換えて「会話へ送る」の ▶。\n"
    "話しかけたのと同じに AI が受け取る（会話コマンドが稼働中であること）。\n"
    "音声ファイルなら: 音声 → 文字起こし（Whisper）→ 会話へ送る\n"
    "動画なら: 動画 → 音声抽出（ffmpeg）→ 文字起こし → 会話へ送る",
    60, 1080, width=360)
send_src = p.file("音声/送るテキスト.txt", "英語にして、明日は晴れです", 470, 1150,
                  memo="ここを書き換えて右の ▶")
send = p.builtin("会話へ送る", 700, 1150, name="voice_send", accept_mime="text/*",
                 memo="テキストを稼働中の会話コマンドへ渡す（出力カードは作らない）")
p.flow(send_src, send)

# ════════════════════════════════════════════════════════════════
# B. 口述
# ════════════════════════════════════════════════════════════════
p.shape(20, 1360, 1560, 560, "B. 口述 — 話すたびに2本が同時に走る", fill="#4a90d9", opacity=0.10)
p.note(
    "使い方（口述）\n"
    "1. A の「会話コマンド」を停止してから、「口述」の ▶ 稼働開始\n"
    "   （マイクは1つ＝稼働できる音声カードは1枚）\n"
    "2. 普通に話す。話し終えるたびに全文が 口述.txt に入り、\n"
    "   矢印の先の2枚が同時に走る:\n"
    "   ・清書 → 清書001, 002 … と溜まる\n"
    "   ・キーワード → 最新の発話のキーワードで上書き\n"
    "・AI の判定は通らない（全部の分岐へそのまま渡す）\n"
    "・返事はしない。完了の報告だけ声で返る",
    60, 1420, width=360)
dic = p.voice("口述", 470, 1430, mode="dictation", say_out="音声/口述.txt")
dic_in = p.file("音声/口述.txt", "", 700, 1430, memo="話した全文が入る受け皿（口述モード）")
p.request(dic, dic_in)  # 「書き出し」
clean_role = p.note(
    "役割：清書係（ここを書き換える）\n"
    "入力は音声認識の結果。誤認識を文脈で直し、句読点を整え、\n"
    "話した内容は足さず削らずに清書した本文だけを出す。",
    470, 1630, width=300)
clean_ai = p.ai("清書", 950, 1560, prefix="清書", seq=1, temperature=0.2)
kw_role = p.note(
    "役割：キーワード係（ここを書き換える）\n"
    "入力は音声認識の結果。大事な語を3〜5個、\n"
    "読点区切りの1行で出す。",
    470, 1790, width=300)
kw_ai = p.ai("キーワード", 950, 1760, prefix="キーワード", temperature=0.2)
p.flow(dic_in, clean_ai)
p.flow(clean_role, clean_ai, role="system")
p.flow(dic_in, kw_ai)
p.flow(kw_role, kw_ai, role="system")
p.request(dic, clean_ai)
p.request(dic, kw_ai)

p.view(0, 0, 0.55)
p.save(reset=a.reset)
